#!/bin/bash
# ==============================================================================
# scripts/bootstrap_airflow.sh
# Role: EC2 User Data Bootstrap Script — runs ONCE on first boot
#
# WHAT THIS DOES:
# 1. Updates system packages
# 2. Installs Docker Engine + Docker Compose plugin
# 3. Creates Airflow directories and configuration
# 4. Writes the docker-compose.yml with environment-specific values
# 5. Initialises the Airflow metadata database
# 6. Starts Airflow (Webserver + Scheduler) in the background
# 7. Syncs DAG files from the S3 artifacts bucket
#
# TEMPLATE VARIABLES (injected by Terraform's templatefile()):
#   ${project_name}         — "urbanpulse"
#   ${environment}          — "dev" | "prod"
#   ${aws_region}           — "us-east-1"
#   ${s3_artifacts_bucket}  — "urbanpulse-artifacts-dev"
#   ${airflow_version}      — "2.8.0"
#   ${fernet_key_param}     — SSM Parameter Store path for the Airflow Fernet key
#   ${db_password_param}    — SSM Parameter Store path for the Postgres password
# ==============================================================================

set -euo pipefail  # Exit on any error, undefined variable, or pipe failure

# ── Log all output to /var/log/user-data.log for debugging ─────────────────
exec > >(tee /var/log/user-data.log | logger -t user-data) 2>&1
echo "=== UrbanPulse Airflow Bootstrap Started: $(date) ==="

# ── 1. System Update ────────────────────────────────────────────────────────
echo "--- Updating system packages ---"
dnf update -y
dnf install -y aws-cli jq git

# ── 2. Install Docker ───────────────────────────────────────────────────────
echo "--- Installing Docker ---"
dnf install -y docker
systemctl start docker
systemctl enable docker

# Install Docker Compose plugin (v2 style: `docker compose`)
mkdir -p /usr/local/lib/docker/cli-plugins
curl -SL "https://github.com/docker/compose/releases/download/v2.24.5/docker-compose-linux-x86_64" \
     -o /usr/local/lib/docker/cli-plugins/docker-compose
chmod +x /usr/local/lib/docker/cli-plugins/docker-compose

# Add ec2-user to docker group so DAG syncing doesn't need sudo
usermod -aG docker ec2-user

# ── 3. Retrieve Secrets from SSM Parameter Store ────────────────────────────
echo "--- Fetching secrets from SSM ---"
FERNET_KEY=$(aws ssm get-parameter \
  --name "${fernet_key_param}" \
  --with-decryption \
  --region "${aws_region}" \
  --query "Parameter.Value" \
  --output text 2>/dev/null || echo "changeme-generate-with-fernet")

DB_PASSWORD=$(aws ssm get-parameter \
  --name "${db_password_param}" \
  --with-decryption \
  --region "${aws_region}" \
  --query "Parameter.Value" \
  --output text 2>/dev/null || echo "airflow_db_pass_$(date +%s)")

# ── 4. Create Airflow Directories ───────────────────────────────────────────
echo "--- Creating Airflow directory structure ---"
mkdir -p /opt/airflow/{dags,logs,plugins,config}
chown -R 50000:50000 /opt/airflow  # UID 50000 is the default Airflow user in the Docker image

# ── 5. Write docker-compose.yml ─────────────────────────────────────────────
echo "--- Writing docker-compose.yml ---"
cat > /opt/airflow/docker-compose.yml << EOF
# UrbanPulse Airflow — Docker Compose
# Generated by Terraform bootstrap script
version: '3.8'

x-airflow-common: &airflow-common
  image: apache/airflow:${airflow_version}
  environment:
    AIRFLOW__CORE__EXECUTOR: LocalExecutor
    AIRFLOW__DATABASE__SQL_ALCHEMY_CONN: postgresql+psycopg2://airflow:$${DB_PASSWORD}@postgres:5432/airflow
    AIRFLOW__CORE__FERNET_KEY: '$${FERNET_KEY}'
    AIRFLOW__CORE__LOAD_EXAMPLES: 'false'
    AIRFLOW__WEBSERVER__SECRET_KEY: '$${FERNET_KEY}'
    AIRFLOW__LOGGING__REMOTE_LOGGING: 'true'
    AIRFLOW__LOGGING__REMOTE_BASE_LOG_FOLDER: s3://${s3_artifacts_bucket}/airflow-logs/${environment}
    AIRFLOW__LOGGING__REMOTE_LOG_CONN_ID: aws_default
    AWS_DEFAULT_REGION: ${aws_region}
    AIRFLOW_CONN_AWS_DEFAULT: 'aws://'  # Uses EC2 instance profile (no keys needed)
  volumes:
    - /opt/airflow/dags:/opt/airflow/dags
    - /opt/airflow/logs:/opt/airflow/logs
    - /opt/airflow/plugins:/opt/airflow/plugins
    - /opt/airflow/config:/opt/airflow/config
  depends_on:
    postgres:
      condition: service_healthy

services:
  postgres:
    image: postgres:15
    environment:
      POSTGRES_USER: airflow
      POSTGRES_PASSWORD: $${DB_PASSWORD}
      POSTGRES_DB: airflow
    volumes:
      - postgres_data:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD", "pg_isready", "-U", "airflow"]
      interval: 10s
      retries: 5
      start_period: 5s

  airflow-webserver:
    <<: *airflow-common
    command: webserver
    ports:
      - "8080:8080"
    healthcheck:
      test: ["CMD", "curl", "--fail", "http://localhost:8080/health"]
      interval: 30s
      timeout: 10s
      retries: 5
    restart: always

  airflow-scheduler:
    <<: *airflow-common
    command: scheduler
    restart: always

  airflow-init:
    <<: *airflow-common
    command: >
      bash -c "
        airflow db upgrade &&
        airflow users create
          --username admin
          --firstname Admin
          --lastname User
          --role Admin
          --email admin@urbanpulse.io
          --password admin
      "
    restart: on-failure

volumes:
  postgres_data:
EOF

# ── 6. Start Airflow ─────────────────────────────────────────────────────────
echo "--- Starting Airflow ---"
cd /opt/airflow

# Export variables for docker-compose
export DB_PASSWORD="$DB_PASSWORD"
export FERNET_KEY="$FERNET_KEY"

docker compose up airflow-init
docker compose up -d airflow-webserver airflow-scheduler

echo "--- Airflow started ---"

# ── 7. Sync DAGs from S3 ────────────────────────────────────────────────────
echo "--- Syncing DAGs from S3 artifacts bucket ---"
aws s3 sync "s3://${s3_artifacts_bucket}/dags/" /opt/airflow/dags/ --region "${aws_region}" || true

# Set up a cron job to sync DAGs every 5 minutes
(crontab -l 2>/dev/null; echo "*/5 * * * * aws s3 sync s3://${s3_artifacts_bucket}/dags/ /opt/airflow/dags/ --region ${aws_region}") | crontab -

echo "=== UrbanPulse Airflow Bootstrap Complete: $(date) ==="
echo "Airflow UI will be available at: http://$(curl -s http://169.254.169.254/latest/meta-data/public-ipv4):8080"
echo "Login: admin / admin (change immediately in production!)"
